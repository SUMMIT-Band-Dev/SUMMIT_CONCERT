-- SET LOCAL lock_timeout = '5s';
-- DROP TABLE "InfoItem";
-- DROP TABLE "InfoSection";
-- DROP TABLE "Ticket";
-- DROP TABLE "PerformanceDay";
-- DROP TABLE "Concert";
-- DROP TABLE "Venue";
-- DROP TYPE "info_section_category";
